// Generate 30 days of sample timesheet data for 10 employees
function generateTimesheetDays(patternIndex: number): TimesheetDayEntry[] {
  const days: TimesheetDayEntry[] = [];
  for (let d = 1; d <= 30; d++) {
    // Determine weekday: November 2026 starts on Sunday (1 = Sun, 2 = Mon, ..., 7 = Sat, 8 = Sun)
    // Date: 2026-11-d
    const dayOfWeek = new Date(2026, 10, d).getDay(); // 0 is Sun

    let code: TimesheetDayCode | string = 'X';
    let highlight: TimesheetCellHighlight = 'none';

    if (dayOfWeek === 0) {
      // Sunday
      if (patternIndex % 3 === 0 && d === 15) {
        code = 'W_OFF';
        highlight = 'worked_off_day';
      } else {
        code = 'OFF';
      }
    } else if (d === 10 && patternIndex === 1) {
      code = 'AL';
      highlight = 'confirmed';
    } else if (d === 12 && patternIndex === 2) {
      code = 'UL';
      highlight = 'rejected';
    } else if (d === 14 && patternIndex === 3) {
      code = 'Q';
      highlight = 'absent';
    } else if (d === 18 && patternIndex === 4) {
      code = '02:53';
      highlight = 'not_checked_out';
    } else if (d === 20 && patternIndex === 5) {
      code = 'X/2';
      highlight = 'none';
    }

    days.push({ day: d, code, highlight });
  }
  return days;
}

